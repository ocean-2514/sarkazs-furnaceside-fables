// 142 魔王的床榻：目标生命值达到上限时，每回合开始获得10点格挡
public sealed class SarkazKingsRegalRest : RelicModel
{
    public override RelicRarity Rarity => RelicRarity.Common;

    public override async Task AfterSideTurnStart(CombatSide side, IReadOnlyList<Creature> participants, ICombatState combatState)
    {
        if (side != Owner.Creature.Side) return;
        if (Owner.Creature.CurrentHp < Owner.Creature.MaxHp) return;
        Flash();
        await CreatureCmd.GainBlock(Owner.Creature, 10, ValueProp.Unpowered, null);
    }
}
