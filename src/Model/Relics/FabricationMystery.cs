// 161 惧傲之谜：第一回合获得10点能量，第二回合开始每回合失去1点能量，仅诡谲断章内生效。所有敌人生命值+10%。
public sealed class FabricationMystery : FragmentMysteryRelic
{
    protected override async Task OnPlayerTurnStartInFragment(ICombatState combatState)
    {
        if (combatState.RoundNumber == 1)
        {
            await PlayerCmd.GainEnergy(10, Owner);
        }
        else
        {
            await PlayerCmd.LoseEnergy(1, Owner);
        }
    }
}
