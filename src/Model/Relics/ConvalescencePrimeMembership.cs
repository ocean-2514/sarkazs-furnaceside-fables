// 101 疗养特供卡：第一回合攻击速度+70
public sealed class ConvalescencePrimeMembership : RelicModel
{
    public override RelicRarity Rarity => RelicRarity.Uncommon;

    public override async Task BeforeCombatStart()
    {
        await SarkazRelicFx.ApplySelf<AttackSpeed>(this, 70);
    }

    public override async Task AfterSideTurnEnd(PlayerChoiceContext choiceContext, CombatSide side, IEnumerable<Creature> participants)
    {
        if (side != Owner.Creature.Side || Owner.Creature.CombatState.RoundNumber != 1) return;
        await SarkazRelicFx.ApplySelf<AttackSpeed>(this, -70);
    }
}
