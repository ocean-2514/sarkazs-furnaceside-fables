// 157 滚动先祖：所有敌方单位的攻击速度+30，最大生命值+30%（移动速度无对应机制，忽略）
public sealed class RollingAncestors : EnemyDebuffRelic
{
    public override RelicRarity Rarity => RelicRarity.Event;

    protected override async Task ApplyToEnemy(Creature enemy)
    {
        await SarkazRelicFx.ApplyPower<AttackSpeed>(this, enemy, 30);
        await CreatureCmd.GainMaxHp(enemy, enemy.MaxHp * 30 / 100);
    }
}
