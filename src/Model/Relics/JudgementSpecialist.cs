// 181 论断：特种：每拥有一个仅在诡谲断章生效的收藏品，第一回合多抽1张牌
public sealed class JudgementSpecialist : RelicModel
{
    public override RelicRarity Rarity => RelicRarity.Common;

    public override decimal ModifyHandDraw(Player player, decimal count)
    {
        if (player != Owner || player.Creature.CombatState.RoundNumber > 1) return count;
        int n = Owner.Relics.Count(r => r is IFragmentMystery);
        return count + n;
    }
}
