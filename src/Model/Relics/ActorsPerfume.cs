// 075 演出用香水：每回合回复2%的最大生命值
public sealed class ActorsPerfume : RelicModel
{
    public override RelicRarity Rarity => RelicRarity.Uncommon;

    public override async Task AfterSideTurnStart(CombatSide side, IReadOnlyList<Creature> participants, ICombatState combatState)
    {
        if (side != Owner.Creature.Side) return;
        decimal amount = Owner.Creature.MaxHp * 2 / 100;
        if (amount > 0) await CreatureCmd.Heal(Owner.Creature, amount);
    }
    public override async Task BeforeCombatStart()
    {
        await SarkazRelicFx.ApplySelf<ActorsPerfumePower>(this, 1);
    }
}
