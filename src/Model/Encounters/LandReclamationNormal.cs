using Skz.Ocean.Model.Monsters;

namespace Skz.Ocean.Model.Encounters;

public sealed class LandReclamationNormal : SarkazEncounterModel
{
    public override RoomType RoomType => RoomType.Monster;

    public override IEnumerable<MonsterModel> AllPossibleMonsters => [
        ModelDb.Monster<SteamTank>(),
        ModelDb.Monster<LondiniumMobileDefenseArtillery>()
    ];

    protected override IReadOnlyList<IReadOnlyList<WaveEntry>> GenerateWaves()
    {
        return [
            [
                new WaveEntry(() => ModelDb.Monster<SteamTank>(), "first"),
                new WaveEntry(() => ModelDb.Monster<LondiniumMobileDefenseArtillery>(), "second")
            ]
        ];
    }
}
